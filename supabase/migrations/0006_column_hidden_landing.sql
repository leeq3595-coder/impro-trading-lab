-- 칼럼 "히든 랜딩페이지" 지원
-- 인스타 릴스 → 자동DM → 정보성 랜딩페이지 → 소통방 전환 퍼널용.
-- is_hidden=true인 칼럼은 홈/칼럼목록 어디에도 노출되지 않고,
-- 직접 링크(/columns/[id])로만 들어갈 수 있어요. 로그인 여부와 무관하게
-- 공개(VIP 아닌 이상) — 콜드 트래픽 유입용이라 로그인 장벽이 없어야 해요.
-- =========================================================
alter table public.columns
  add column if not exists is_hidden boolean not null default false;
